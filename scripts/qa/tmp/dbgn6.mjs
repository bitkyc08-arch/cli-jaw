import { openFixture, startFixtureServer } from '../fixture-lib.mjs';
const server = await startFixtureServer();
const { browser, page } = await openFixture(server.url, { historyCount: 10 });
await page.evaluate(() => { window.__jawE2E.resetNotes(); window.__jawE2E.setNotes({ fileConflict: true }); });
await page.evaluate(() => window.__jawE2E.openPanel('notes'));
await page.waitForTimeout(1000);
await page.locator('.d2-notes-tree-item[role="treeitem"]:has-text("daily")').click();
await page.waitForTimeout(400);
await page.locator('.d2-notes-tree-item[role="treeitem"]:has-text("today.md")').click();
await page.waitForTimeout(1200);
console.log('TEXTAREA:', await page.evaluate(() => document.querySelector('.d2-notes-textarea') ? 'present' : 'MISSING'));
console.log('DIRTY:', await page.evaluate(() => document.querySelector('.d2-notes-dirty') ? 'dirty' : 'clean'));
await page.locator('.d2-notes-textarea').fill('# wp5c edit\n');
await page.waitForTimeout(300);
console.log('DIRTY after edit:', await page.evaluate(() => document.querySelector('.d2-notes-dirty') ? 'dirty' : 'clean'));
console.log('SAVE disabled:', await page.evaluate(() => document.querySelector('.d2-notes-save-button')?.disabled));
const mark = await page.evaluate(() => window.__jawE2E.markRequests());
await page.locator('.d2-notes-save-button:not([disabled])').click();
await page.waitForTimeout(1200);
console.log('CONFLICT NOTICE:', await page.evaluate(() => document.querySelector('.d2-notes-notice.is-conflict')?.outerHTML?.slice(0,150) ?? 'none'));
console.log('REQS:', await page.evaluate((s) => window.__jawE2E.allRequests(s).map(r=>r.method+' '+r.pathname), mark));
await browser.close(); await server.close();
