import { openFixture, startFixtureServer } from '../fixture-lib.mjs';
const server = await startFixtureServer();
const { browser, page } = await openFixture(server.url, { historyCount: 10 });
await page.evaluate(() => { window.__jawE2E.resetSettings(); window.__jawE2E.setSettings({ holdRegistry: true }); });
await page.evaluate(() => window.__jawE2E.setSettings());
await page.waitForTimeout(1500);
console.log('WORKSPACE:', await page.evaluate(() => document.querySelector('.d2-settings-workspace') ? 'present' : 'MISSING'));
console.log('STATES:', await page.evaluate(() => [...document.querySelectorAll('[class*="d2-settings"]')].slice(0,6).map(e=>e.className)));
console.log('SHELL:', await page.evaluate(() => document.querySelector('.d2-settings-state, .d2-settings-content')?.outerHTML?.slice(0,200) ?? 'none'));
await browser.close(); await server.close();
